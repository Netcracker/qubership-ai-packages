#!/usr/bin/env python3
"""Print a map of the code a change touches, for planning how to split the review between subagents.

Usage: code-map.py --diff-base <base> [--repo <repo>] [--exclude <pathspec>]...

<repo> is a checkout at the reviewed head, the current directory by default. An --exclude pathspec drops the paths the
request put out of scope. The map lists the lines the change adds per directory, by kind: code, tests, documentation,
data, configuration, and generated or lock files. Then, per changed code file, it gives the added line ranges at head
(or the number of lines it removes, where it adds none), the top-level declarations with their line ranges, and the
other changed files that use each declaration; per changed test file, its added line ranges and the code files whose
declarations it uses. The deleted files with their kind, and the symlinks, submodules, and binary files the map skips
are listed last.

Declarations and references come from sb, the CLI of ast-bro: `sb map` outlines a file, and `sb callers` lists the
calls, constructions, and implementations of a declaration, or of the members of a type, from its syntax tree. The
references are a lower bound. sb does not record a type named only in a signature or a field, and a call whose receiver
it cannot type counts only where this declaration is the call's one candidate; a declaration with such calls left out
says how many. Where `sb` is not on PATH, or `sb map` fails, the map has no declarations and no references; where
`sb callers` fails for some declarations, they are listed without references. Either way a note goes to stderr. sb keeps
its index in `.ast-bro/` at the root of <repo>, which it hides from git.
"""
import argparse
import collections
import concurrent.futures
import json
import os
import re
import shutil
import subprocess
import sys

LOCK_NAMES = {"go.sum", "package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "Cargo.lock",
              "Gemfile.lock", "poetry.lock", "composer.lock", "Pipfile.lock", "uv.lock", "gradle.lockfile"}
TEST_PATH = re.compile(r"(^|/)(tests?|testdata|__tests__|spec)/|_test\.\w+$|(^|/)test_[^/]*$|"
                       r"(Test|Tests|IT|Spec)\.\w+$|\.(test|spec)\.\w+$")
GENERATED = re.compile(r"Code generated .* DO NOT EDIT|@generated|<auto-generated")
EXTENSIONS = {
    "docs": {"md", "markdown", "rst", "adoc", "txt", "html", "htm"},
    "data": {"json", "csv", "tsv", "ndjson", "jsonl", "svg"},
    "config": {"yaml", "yml", "toml", "ini", "properties", "conf", "cfg", "xml", "env"},
}
# Files with no extension that are not code, by their whole name in any case. Any file no rule matches counts as code:
# a file wrongly counted adds its lines to the size gate, while code wrongly left out is never assigned to a reviewer.
NAMES = {"license": "docs", "licence": "docs", "notice": "docs", "copying": "docs", "authors": "docs",
         "contributors": "docs", "codeowners": "docs", "readme": "docs", "changelog": "docs", "changes": "docs",
         "version": "docs", "todo": "docs", "go.mod": "config", "go.work": "config"}
KINDS = {"code": "Code", "test": "Tests", "docs": "Docs", "data": "Data", "config": "Config",
         "generated": "Generated or lock"}
# The kinds of declaration, as `sb map` spells them, that sb callers resolves. It does not resolve a field, which is also
# how sb reports a constant, a variable, and a type alias, nor a delegate, a property, or an enum member.
CALLABLE = {"function", "method", "ctor"}
TYPES = {"class", "struct", "interface", "enum", "record"}
# sb callers runs this many at a time.
WORKERS = 8
# At most this many referencing files are listed per declaration; the rest are counted.
MAX_REFS = 12
# sb gets the paths in batches of this size, so a broad change stays under the argument-size limit.
BATCH = 200
SKIPPED_MODES = {"120000": "symlink", "160000": "submodule"}
# Seconds one sb run may take: a map of one batch, or callers of one name, the first of which builds the index.
SB_TIMEOUT = 600
# sb callers lists at most this many calls; its default, 200, would drop the users of a widely called declaration.
CALLERS_LIMIT = 100000


def git(repo, *args, stdin=None):
    return subprocess.run(["git", "-C", repo, *args], capture_output=True, check=True, input=stdin).stdout


def entries(repo, base, excludes):
    """Yield (status, mode, old path, new path) for every entry the change touches, from NUL-separated output."""
    spec = ["--", "."] + [f":(exclude){e}" for e in excludes] if excludes else []
    fields = git(repo, "diff", "--raw", "-z", "-M", f"{base}...HEAD", *spec).split(b"\0")
    i = 0
    while i < len(fields) and fields[i]:
        meta = fields[i].decode().split()
        status, mode = meta[4], meta[1]
        old = fields[i + 1].decode("utf-8", "surrogateescape")
        if status[0] in "RC":
            new = fields[i + 2].decode("utf-8", "surrogateescape")
            i += 3
        else:
            new = old
            i += 2
        yield status[0], mode, old, new


def changed_lines(repo, base, old, new):
    """Return (added line ranges at head as [(first, last)], number of removed lines), or None for a binary file."""
    paths = [old, new] if old != new else [new]
    # An external diff or a textconv driver would replace the hunks this parses.
    patch = git(repo, "diff", "-U0", "-M", "--no-color", "--no-ext-diff", "--no-textconv", f"{base}...HEAD", "--",
                *paths)
    if re.search(rb"^Binary files ", patch, re.M):
        return None
    ranges, removed = [], 0
    # A count left out of a hunk header means one line.
    for m in re.finditer(rb"^@@ -\d+(?:,(\d+))? \+(\d+)(?:,(\d+))? @@", patch, re.M):
        removed += int(m.group(1) or 1)
        start, n = int(m.group(2)), int(m.group(3) or 1)
        if n:
            ranges.append((start, start + n - 1))
    return ranges, removed


def generated_by_attribute(repo, paths):
    if not paths:
        return set()
    out = git(repo, "check-attr", "--stdin", "-z", "linguist-generated",
              stdin="\0".join(paths).encode("utf-8", "surrogateescape") + b"\0").split(b"\0")
    return {out[i].decode("utf-8", "surrogateescape") for i in range(0, len(out) - 2, 3)
            if out[i + 2] in (b"true", b"set")}


def kind(repo, path, attr_generated, at_head=True):
    """Classify a path; a path not at head, such as a deleted file, is classified without its generated header."""
    if os.path.basename(path) in LOCK_NAMES or path.endswith(".lock") or path in attr_generated:
        return "generated"
    head = ""
    if at_head:
        try:
            with open(os.path.join(repo, path), encoding="utf-8", errors="replace") as f:
                head = "".join(f.readline() for _ in range(10))
        except OSError:
            pass
    if GENERATED.search(head):
        return "generated"
    name = os.path.basename(path)
    if name.startswith(".") and name.count(".") == 1:
        return "config"
    ext = name.rsplit(".", 1)[-1].lower() if "." in name else ""
    for k, exts in EXTENSIONS.items():
        if ext in exts:
            return k
    # After the extensions, so that a fixture such as testdata/golden.json counts as data, not as a test to read.
    if TEST_PATH.search(path):
        return "test"
    return NAMES.get(name.lower(), "code")


def sb(repo, *args):
    """Run sb in repo and return (exit code, parsed JSON output), or (None, None) where it timed out."""
    try:
        result = subprocess.run(["sb", *args], cwd=repo, capture_output=True, timeout=SB_TIMEOUT)
    except subprocess.TimeoutExpired:
        return None, None
    try:
        return result.returncode, json.loads(result.stdout)
    except ValueError:
        return result.returncode, None


def unwrap(decls):
    """Replace a package or namespace, nested ones included, with the declarations it holds."""
    out = []
    for d in decls:
        out.extend(unwrap(d.get("children", ())) if d["kind"] == "namespace" else [d])
    return out


def outline(repo, paths):
    """Return {path: top-level declarations} from sb, or None where sb is missing or fails."""
    if not shutil.which("sb"):
        print("code-map: sb is not on PATH; the map has no declarations."
              " sb is the CLI of ast-bro: https://github.com/aeroxy/ast-bro", file=sys.stderr)
        return None
    out = {}
    for i in range(0, len(paths), BATCH):
        code, found = sb(repo, "map", "--json", "--compact", *paths[i:i + BATCH])
        if not isinstance(found, dict) or "files" not in found:
            status = "timed out" if code is None else f"exited with {code}"
            print(f"code-map: sb map {status}; the map has no declarations", file=sys.stderr)
            return None
        for f in found["files"]:
            out[f["path"]] = unwrap(f["declarations"])
    return out


def callers(repo, path, decl):
    """Return (files, calls left out, failed) for a declaration, or for a type and its members, by sb callers.

    The files call, construct, or implement it. A call whose receiver sb cannot type counts where this declaration is its
    only candidate; the calls left out are the other such calls, including those past sb's sample of them. Failed is true
    where an sb run timed out, crashed, or found no such symbol.
    """
    targets = [decl["name"]]
    if decl["kind"] in TYPES:
        targets += [c["name"] for c in decl.get("children", ()) if c["kind"] in CALLABLE]
    elif decl["kind"] not in CALLABLE:
        return set(), 0, False
    # --file matches a path suffix, so a root-level main.go also names sub/main.go; keep this file's declaration only.
    own = path + "::"
    files, left_out, failed = set(), 0, False
    for target in targets:
        _, found = sb(repo, "callers", "--file", path, "--symbol", target, "--json", "--compact",
                         "--limit", str(CALLERS_LIMIT))
        if not isinstance(found, dict) or "matches" not in found:
            failed = True
            continue
        files.update(m["file"] for m in found["matches"] if m.get("target", "").startswith(own))
        for t in found.get("types", ()):
            if t.get("qn", "").startswith(own):
                files.update(c["file"] for c in t.get("constructions", []) + t.get("implementations", []) if "file" in c)
        attributed = [u for u in found.get("unattributed", ())
                      if len(u.get("candidates", ())) == 1 and u["candidates"][0].startswith(own)]
        files.update(u["file"] for u in attributed)
        left_out += max(found.get("unattributed_total", 0) - len(attributed), 0)
    return files, left_out, failed


def n_lines(n):
    return f"{n} line" if n == 1 else f"{n} lines"


def fmt_ranges(ranges):
    return ", ".join(f"{a}-{b}" if a != b else str(a) for a, b in ranges)


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--diff-base", required=True)
    p.add_argument("--repo", default=".")
    p.add_argument("--exclude", action="append", default=[])
    args = p.parse_args()
    repo = args.repo

    changed, removed, deleted, skipped = {}, {}, [], []
    for status, mode, old, new in entries(repo, args.diff_base, args.exclude):
        if status == "D":
            deleted.append(old)
        elif mode in SKIPPED_MODES:
            skipped.append(f"{new} ({SKIPPED_MODES[mode]})")
        else:
            lines = changed_lines(repo, args.diff_base, old, new)
            if lines is None:
                skipped.append(f"{new} (binary)")
            else:
                changed[new], removed[new] = lines

    attr_generated = generated_by_attribute(repo, list(changed) + deleted)
    kinds = {path: kind(repo, path, attr_generated) for path in changed}
    added = {path: sum(b - a + 1 for a, b in r) for path, r in changed.items()}
    by_dir = collections.defaultdict(collections.Counter)
    for path, n in added.items():
        by_dir[os.path.dirname(path) or "."][kinds[path]] += n

    print("# Code map\n")
    print("Added lines per directory.\n")
    print("| Directory | " + " | ".join(KINDS.values()) + " |")
    print("| --- |" + " --- |" * len(KINDS))
    total = collections.Counter()
    for d, c in sorted(by_dir.items(), key=lambda x: (-x[1]["code"], x[0])):
        total.update(c)
        print(f"| `{d}` | " + " | ".join(str(c[k]) for k in KINDS) + " |")
    print("| total | " + " | ".join(str(total[k]) for k in KINDS) + " |\n")

    # A file that only removes lines is listed too: a shard still owns it.
    code = sorted(p for p in changed if kinds[p] == "code" and (added[p] or removed[p]))
    tests = sorted(p for p in changed if kinds[p] == "test" and (added[p] or removed[p]))
    decls = (outline(repo, code) if code else {}) or {}
    jobs = [(path, d) for path in code for d in decls.get(path, ())]
    refs = {}
    # The first sb callers run builds sb's index; the others then read it at once, rather than each building its own.
    first = next((i for i, (_, d) in enumerate(jobs) if d["kind"] in CALLABLE | TYPES), None)
    if first is not None:
        refs[first] = callers(repo, *jobs[first])
    with concurrent.futures.ThreadPoolExecutor(WORKERS) as pool:
        rest = [i for i in range(len(jobs)) if i != first]
        refs.update(zip(rest, pool.map(lambda i: callers(repo, *jobs[i]), rest)))
    failed = sum(refs[i][2] for i in refs)
    if failed:
        print(f"code-map: sb callers failed for {failed} declarations; they are listed without references",
              file=sys.stderr)
    listed_in = set(code + tests)
    refs_of = {(path, d["name"]): sorted(refs[i][0] & listed_in - {path}) for i, (path, d) in enumerate(jobs)}
    left_out = {(path, d["name"]): refs[i][1] for i, (path, d) in enumerate(jobs)}
    failed_of = {(path, d["name"]) for i, (path, d) in enumerate(jobs) if refs[i][2]}

    def listed(paths):
        """Join paths, writing the files of one directory once as `dir/{a, b}`."""
        more = f" and {len(paths) - MAX_REFS} more" if len(paths) > MAX_REFS else ""
        by_dir = collections.defaultdict(list)
        for q in paths[:MAX_REFS]:
            by_dir[os.path.dirname(q)].append(os.path.basename(q))
        parts = [os.path.join(d, base[0]) if len(base) == 1 else f"{d + '/' if d else ''}{{{', '.join(base)}}}"
                 for d, base in by_dir.items()]
        return "; ".join(parts) + more

    for path in code:
        print(f"## {path} (+{added[path]})\n")
        print(f"Added: {fmt_ranges(changed[path]) or f'none (removes {n_lines(removed[path])})'}\n")
        for d in decls.get(path, ()):
            key = path, d["name"]
            notes = [f"used in {listed(refs_of[key])}"] if refs_of[key] else []
            if left_out[key]:
                notes.append(f"{left_out[key]} calls sb did not attribute")
            if key in failed_of:
                notes.append("sb callers failed")
            used = ": " + "; ".join(notes) if notes else ""
            print(f"- {d['kind']} `{d['name']}` lines {d['start_line']}-{d['end_line']}{used}")
        print()
    if tests:
        print("## Tests\n")
        for path in tests:
            # A test belongs with the code files whose declarations it uses.
            named = sorted({q for (q, _), users in refs_of.items() if path in users})
            used = f": uses declarations of {listed(named)}" if named else ""
            ranges = f"added {fmt_ranges(changed[path])}" if changed[path] else f"removes {n_lines(removed[path])}"
            print(f"- {path} (+{added[path]}), {ranges}{used}")
        print()
    if deleted:
        print("## Deleted\n")
        for path in sorted(deleted):
            print(f"- {path} ({KINDS[kind(repo, path, attr_generated, at_head=False)].lower()})")
        print()
    if skipped:
        print("## Skipped\n")
        for item in sorted(skipped):
            print(f"- {item}")


if __name__ == "__main__":
    main()
